"""Turn compiled .spv files into one C header of uint32_t arrays.

Usage: embed_spirv.py OUT.h a.spv b.spv ...
Each file becomes `static const uint32_t <stem>_spv[]` plus `<stem>_spv_size`
(in bytes), so the probes need no file access on the console.
"""
import pathlib
import struct
import sys


def main() -> int:
    out = pathlib.Path(sys.argv[1])
    lines = ["/* Generated by tools/embed_spirv.py. Do not edit. */", "#pragma once", "#include <stdint.h>", ""]
    for name in sys.argv[2:]:
        path = pathlib.Path(name)
        data = path.read_bytes()
        if len(data) % 4 or struct.unpack_from("<I", data)[0] != 0x07230203:
            print(f"{name}: not a SPIR-V module", file=sys.stderr)
            return 1
        words = struct.unpack(f"<{len(data) // 4}I", data)
        stem = path.stem
        lines.append(f"static const uint32_t {stem}_spv[] = {{")
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 8]) + ",")
        lines.append("};")
        lines.append(f"static const uint32_t {stem}_spv_size = {len(data)}u;")
        lines.append("")
    out.write_text("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
